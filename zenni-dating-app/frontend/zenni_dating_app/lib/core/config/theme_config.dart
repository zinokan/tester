        backgroundColor: Color(0xFF1A202C),
        selectedItemColor: primaryColor,
        unselectedItemColor: Color(0xFFA0AEC0),
        type: BottomNavigationBarType.fixed,
        elevation: 8,
      ),
    );
  }
}